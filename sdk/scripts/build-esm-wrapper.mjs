#!/usr/bin/env node
/**
 * Writes `dist/index.mjs`: an ES module that re-exports the CommonJS build (`dist/index.js`).
 *
 * It is a wrapper, not a second build, on purpose: a real dual build would load two copies of the package in an
 * application that mixes `import` and `require`, each with its own module state. Classes would not satisfy `instanceof`
 * across the copies and the default in-memory `NonceStore` would be two stores, which silently breaks replay protection.
 * With the wrapper there is one copy, and `import { X }` and `require().X` are the same object.
 *
 * Run after `tsc` (`npm run build`). `scripts/check-esm-wrapper.mjs` checks the result.
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const cjs = require(join(root, 'dist', 'index.js'));

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/u;
const names = Object.keys(cjs).filter((name) => name !== 'default' && name !== '__esModule');
const invalid = names.filter((name) => !IDENTIFIER.test(name));
if (invalid.length > 0) {
  throw new Error(`Export names that are not valid identifiers: ${invalid.join(', ')}`);
}

const lines = [
  '// Generated by scripts/build-esm-wrapper.mjs: an ES module view of the CommonJS build (one copy of the package).',
  "import cjs from './index.js';",
  'export default cjs;',
  ...names.map((name) => `export const ${name} = cjs.${name};`)
];
writeFileSync(join(root, 'dist', 'index.mjs'), `${lines.join('\n')}\n`);
console.log(`Wrote dist/index.mjs (${names.length} named exports)`);
